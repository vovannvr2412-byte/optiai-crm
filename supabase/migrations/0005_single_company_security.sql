create table if not exists public.security_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references public.crm_users(id) on delete set null,
  actor_email text not null,
  actor_role text not null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists security_audit_log_created_idx
  on public.security_audit_log(created_at desc);
create index if not exists security_audit_log_actor_idx
  on public.security_audit_log(actor_user_id, created_at desc);

create or replace function public.current_crm_role()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce((
    select role::text
    from public.crm_users
    where auth_user_id = auth.uid() and status = 'active'
    limit 1
  ), '');
$$;

create or replace function public.current_crm_user_id()
returns uuid
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select id
  from public.crm_users
  where auth_user_id = auth.uid() and status = 'active'
  limit 1;
$$;

create or replace function public.can_access_crm_lead(target_owner_id uuid, target_status public.lead_status)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select case public.current_crm_role()
    when 'Руководитель' then true
    when 'РОП' then true
    when 'Менеджер' then target_owner_id = public.current_crm_user_id()
    when 'Аккаунт-менеджер' then target_owner_id = public.current_crm_user_id() and target_status = 'client'
    else false
  end;
$$;

revoke all on function public.current_crm_role() from public, anon;
revoke all on function public.current_crm_user_id() from public, anon;
revoke all on function public.can_access_crm_lead(uuid, public.lead_status) from public, anon;
grant execute on function public.current_crm_role() to authenticated, service_role;
grant execute on function public.current_crm_user_id() to authenticated, service_role;
grant execute on function public.can_access_crm_lead(uuid, public.lead_status) to authenticated, service_role;

