  for insert to authenticated
  with check (
    public.current_crm_role() in ('Руководитель', 'РОП')
    or (public.current_crm_role() = 'Менеджер' and owner_id = public.current_crm_user_id())
  );
create policy "role based lead update" on public.leads
  for update to authenticated
  using (public.can_access_crm_lead(owner_id, status))
  with check (
    public.current_crm_role() in ('Руководитель', 'РОП')
    or (public.current_crm_role() = 'Менеджер' and owner_id = public.current_crm_user_id())
    or (
      public.current_crm_role() = 'Аккаунт-менеджер'
      and owner_id = public.current_crm_user_id()
      and status = 'client'
    )
  );
